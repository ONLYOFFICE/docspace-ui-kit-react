// Builds `docs/components.md` -- the list of every component, what it is for,
// how it is imported and which prop shows and hides it -- from the metadata
// blocks in the component READMEs.
//
//   pnpm readme:catalogue            writes the catalogue
//   pnpm readme:catalogue --check    fails when it is out of date
//
// It is generated rather than maintained because a hand-kept index of 99
// components is a list of things that used to be true. Only the rows between
// the `catalogue:start` / `catalogue:end` markers are written; everything
// around them -- the decision table that says which component fits a job -- is
// written by hand and left alone.
//
// A component whose README has no metadata block yet is not silently dropped:
// it is listed under "Not documented yet", so the catalogue shows the size of
// the remaining work instead of hiding it.

import fs from "node:fs";
import path from "node:path";

import { ROOT, componentFolders } from "./lib/readme-program.mjs";
import { CATEGORIES, parseMetadata } from "./lib/readme-meta.mjs";
import { formatMarkdown } from "./lib/readme-tables.mjs";

const CATALOGUE = path.join(ROOT, "docs", "components.md");

const BLOCK = /<!-- catalogue:start -->[\s\S]*?<!-- catalogue:end -->/;

const usage = () => {
  console.error("usage: node scripts/readme-catalogue.mjs [--check]");
  process.exit(2);
};

const cell = (text) => String(text).replaceAll("|", "\\|");

const code = (text) => `\`${cell(text)}\``;

const collect = () => {
  const documented = [];
  const pending = [];

  for (const folder of componentFolders()) {
    const file = path.join(ROOT, folder, "README.md");

    if (!fs.existsSync(file)) {
      pending.push({ folder, reason: "no README" });
      continue;
    }

    const { meta } = parseMetadata(fs.readFileSync(file, "utf8"));

    if (!meta) {
      pending.push({ folder, reason: "no metadata block" });
      continue;
    }

    documented.push({ folder, meta });
  }

  return { documented, pending };
};

const row = ({ folder, meta }) => {
  const importedAs = meta.import?.barrel ? "barrel or subpath" : "subpath only";

  return [
    "",
    `[${cell(meta.name)}](../${folder}/README.md)`,
    cell(meta.status === "public" ? "public" : "portal-internal"),
    importedAs,
    meta.state?.visibility ? code(meta.state.visibility) : "–",
    cell(meta.summary),
    "",
  ].join(" | ");
};

const catalogue = ({ documented, pending }) => {
  const lines = [
    "<!-- catalogue:start -->",
    "",
    `_Generated by \`pnpm readme:catalogue\` from the metadata block of each component README. Do not edit; edit the README._`,
    "",
  ];

  for (const category of CATEGORIES) {
    const inCategory = documented
      .filter((entry) => entry.meta.category === category)
      .sort((a, b) => a.meta.name.localeCompare(b.meta.name));

    if (inCategory.length === 0) continue;

    lines.push(
      `### ${category}`,
      "",
      "| Component | Status | Import | Shown and hidden by | What it is for |",
      "| --- | --- | --- | --- | --- |",
      ...inCategory.map(row),
      "",
    );
  }

  if (pending.length > 0) {
    lines.push(
      "### Not documented yet",
      "",
      `${pending.length} of ${documented.length + pending.length} folders have no metadata block, so they are not in the tables above. Their READMEs, where they exist, are on the old format.`,
      "",
      ...pending
        .sort((a, b) => a.folder.localeCompare(b.folder))
        .map((entry) => `- \`${entry.folder}\` — ${entry.reason}`),
      "",
    );
  }

  lines.push("<!-- catalogue:end -->");
  return lines.join("\n");
};

const main = async () => {
  const argv = process.argv.slice(2);
  const check = argv.includes("--check");

  if (argv.some((arg) => arg !== "--check")) usage();

  if (!fs.existsSync(CATALOGUE)) {
    console.error(
      `${path.relative(ROOT, CATALOGUE)} does not exist. Create it with a ` +
        "`<!-- catalogue:start -->` / `<!-- catalogue:end -->` pair where the " +
        "tables belong.",
    );
    process.exit(2);
  }

  const current = fs.readFileSync(CATALOGUE, "utf8");

  if (!BLOCK.test(current)) {
    console.error(
      `${path.relative(ROOT, CATALOGUE)} has no \`catalogue:start\` / \`catalogue:end\` block.`,
    );
    process.exit(2);
  }

  const { documented, pending } = collect();
  const rendered = current.replace(BLOCK, () =>
    catalogue({ documented, pending }),
  );
  const formatted = await formatMarkdown(rendered, CATALOGUE);

  if (formatted === current) {
    console.log(
      `docs/components.md is current: ${documented.length} documented, ${pending.length} to go.`,
    );
    return;
  }

  if (check) {
    console.error(
      "docs/components.md is out of date. Run `pnpm readme:catalogue`.",
    );
    process.exit(1);
  }

  fs.writeFileSync(CATALOGUE, formatted, "utf8");
  console.log(
    `wrote docs/components.md: ${documented.length} documented, ${pending.length} to go.`,
  );
};

await main();
