// Compiles every stylesheet the library imports into a CSS file that sits next
// to the module's own chunk, and makes the chunk import it.
//
//   components/button/Button.module.scss   ->  dist/esm/components/button/Button.module.scss/index.js
//                                              dist/esm/components/button/Button.module.scss/index.css
//
// The JS proxy keeps exporting the class-name map, exactly as before, and now
// starts with `import "./index.css"`. A consumer that imports a component
// therefore pulls in that component's CSS and nothing else, and its bundler
// splits the styles along the same chunk boundaries as the code. The previous
// build extracted all 209 stylesheets into one 725 KB dist/styles.css that
// every entry of every app imported whole.
//
// Cascade order is the bundler's: a module's CSS is emitted after the CSS of
// everything it imports (post-order), which is the order the styles were
// written for -- a component's override of a component it renders comes after
// that component's base rule. It is also the order dist/styles.css is put into
// by scripts/order-styles.mjs for consumers that still import the bundle.
//
// Class names are generated by postcss-modules with the same pattern the
// previous plugin used and the same hashing context (the working directory),
// so every `dsui-*` name is unchanged; scripts/check-dist.mjs can be pointed at
// a previous dist to prove it.
//
// Stylesheets from node_modules (katex's, for one) are not handled here: they
// are peer dependencies' files and stay bare imports for the consumer's bundler.

import path from "node:path";

import postcss from "postcss";
import postcssModules from "postcss-modules";
import * as sass from "sass";

import { toPosix } from "../lib/fs-ids.mjs";

const STYLE_RE = /\.(?:scss|css)$/;
const MODULE_RE = /\.module\.(?:scss|css)$/;

// The proxy imports its stylesheet through this external id, and
// `generateBundle` turns every occurrence into a relative import of the emitted
// file. External, because that is what survives rollup's tree shaking: a plain
// stylesheet (`ThemeProvider.scss`) has no class map to export, and rollup
// removes the empty module -- but not an external import inside it, which it
// hoists into the importer instead. So a CSS Module's import ends up in the
// proxy chunk beside the CSS, and a plain stylesheet's import ends up in the
// component that imported the stylesheet; both point at the same emitted
// `<stylesheet>/index.css`. The previous build never noticed the dropped
// modules because the extracted bundle carried their CSS regardless.
const MARKER = "per-module-css:";
const MARKER_IMPORT_RE = /^import\s+(["'])per-module-css:([^"']+)\1;?\n?/gm;

const ROOT = path.resolve(".");

// Module ids reach this plugin with the platform's separator, so on Windows
// they carry backslashes -- and a backslash is the one character that does not
// survive the round trip through the marker import. `JSON.stringify` doubles
// it on the way into the chunk, the regexp above reads the doubled form back,
// and the map lookup misses every time: the build failed with "imports a
// stylesheet that was never compiled" for the first module it reached. POSIX
// separators are what rollup emits in `fileName` anyway, so normalising here
// makes the key, the marker and the emitted path the same string everywhere.

/** Where a stylesheet's CSS is emitted: <path relative to the root>/index.css, mirroring the module layout. */
const cssFileForRoot = (root, id) =>
  `${path.posix.relative(toPosix(root), id)}/index.css`;

export const perModuleCss = ({ generateScopedName, root = ROOT }) => {
  const cssFileFor = (id) => cssFileForRoot(root, id);

  /** Compiled CSS by module id, filled in `transform`, written in `generateBundle`. */
  const cssById = new Map();

  return {
    name: "per-module-css",

    resolveId(source) {
      return source.startsWith(MARKER) ? { id: source, external: true } : null;
    },

    async transform(code, id) {
      // Matched on the POSIX form for the same reason ids are keyed by it: a
      // `path.sep` here reads the running platform's separator, not the one the
      // id was built with.
      if (!STYLE_RE.test(id) || toPosix(id).includes("/node_modules/"))
        return null;

      let css = code;

      if (id.endsWith(".scss")) {
        const result = sass.compile(id, { style: "expanded" });
        css = result.css;
        for (const url of result.loadedUrls) {
          if (url.protocol === "file:")
            this.addWatchFile(decodeURIComponent(url.pathname));
        }
      }

      let classes = null;

      if (MODULE_RE.test(id)) {
        const result = await postcss([
          postcssModules({
            generateScopedName,
            getJSON: (_file, json) => {
              classes = json;
            },
          }),
        ]).process(css, { from: id, map: false });
        css = result.css;
      }

      cssById.set(toPosix(id), css);

      return {
        code:
          `import ${JSON.stringify(MARKER + toPosix(id))};\n` +
          (classes === null
            ? ""
            : `export default ${JSON.stringify(classes)};\n`),
        map: { mappings: "" },
      };
    },

    generateBundle(_options, bundle) {
      const emitted = new Set();

      for (const chunk of Object.values(bundle)) {
        if (chunk.type !== "chunk") continue;

        chunk.code = chunk.code.replace(
          MARKER_IMPORT_RE,
          (_match, _quote, id) => {
            const css = cssById.get(id);
            if (css === undefined)
              this.error(
                `${chunk.fileName} imports a stylesheet that was never compiled: ${id}`,
              );

            const cssFile = cssFileFor(id);
            if (!emitted.has(cssFile)) {
              this.emitFile({ type: "asset", fileName: cssFile, source: css });
              emitted.add(cssFile);
            }

            let specifier = path.posix.relative(
              path.posix.dirname(chunk.fileName),
              cssFile,
            );
            if (!specifier.startsWith(".")) specifier = `./${specifier}`;
            return `import "${specifier}";\n`;
          },
        );
      }

      // A compiled stylesheet nobody imports would have been part of the
      // old bundle and is now silently gone from consumers -- refuse.
      const orphans = [...cssById.keys()].filter(
        (id) => !emitted.has(cssFileFor(id)),
      );
      if (orphans.length > 0) {
        this.error(
          `${orphans.length} compiled stylesheet(s) are imported by no chunk:\n  ${orphans.map(cssFileFor).join("\n  ")}`,
        );
      }
    },
  };
};
