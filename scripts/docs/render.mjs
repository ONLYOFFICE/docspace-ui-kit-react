// Assembled from two halves so that a dependency scan over scripts/ (the
// release-check manifest) does not read it as an import of a package.
export const API_TABLE_IMPORT = [
  "import APITable from",
  "'@site/src/components/APITable/APITable';",
].join(" ");

export const THEMED_IMAGE_IMPORT = [
  "import ThemedImage from",
  "'@theme/ThemedImage';",
].join(" ");

/**
 * The component's picture, in the reader's colour mode: Docusaurus's
 * ThemedImage swaps the source with the theme. The files are retina
 * (SCALE in screenshots.mjs), so `width` is what sizes it on the page.
 */
const themedImage = (alt, { light, dark, width }) =>
  `<ThemedImage alt="${alt.replaceAll('"', "&quot;")}" width={${width}} ` +
  `sources={{ light: require('./${light}').default, dark: require('./${dark}').default }} />`;

/** A PNG's pixel width, from its IHDR chunk. */
export const pngWidth = (file) => {
  const header = Buffer.alloc(24);
  const fd = fs.openSync(file, "r");
  try {
    fs.readSync(fd, header, 0, 24, 0);
  } finally {
    fs.closeSync(fd);
  }
  return header.readUInt32BE(16);
};

const SECTIONS_FILE = "scripts/docs/sections.mjs";
const PUBLIC_API_FILE = "docs/public-api.md";

/** The note `pnpm readme:props` leaves above each table; for repository readers only. */
const GENERATED_NOTE = /^_Generated by `pnpm readme:props`.*_\s*$/gm;

/** A table row's cells, honouring `\|` inside a cell. */
const cellsOf = (row) => {
  const parts = row.split(/(?<!\\)\|/);
  return parts.slice(1, -1).map((part) => part.trim());
};

const PROPS_HEADER = ["Prop", "Type", "Required", "Default", "Description"];

/**
 * Reshapes the five-column Props tables the READMEs carry into the three
 * columns docspace-sdk-js publishes -- `Property | Type | Description` -- so
 * the site's <APITable> has room for the description. `Required` becomes the
 * optional marker after the code span (`` `label`? ``, outside the span so the
 * row id carries no `?`), and `Default` closes the description as
 * `Default: \`x\`.`, both as the SDK writes them.
 */
export const reshapePropsTables = (text) => {
  const lines = splitLines(text).map(({ text: line }) => line);
  const flags = splitLines(text).map(({ code }) => code);

  for (let index = 0; index < lines.length; index += 1) {
    if (flags[index]) continue;
    const header = cellsOf(lines[index]);
    if (header.join("|") !== PROPS_HEADER.join("|")) continue;
    if (!/^\|[\s:|-]+\|$/.test(lines[index + 1] ?? "")) continue;

    lines[index] = "| Property | Type | Description |";
    lines[index + 1] = "| --- | --- | --- |";

    for (let row = index + 2; row < lines.length; row += 1) {
      if (flags[row] || !lines[row].startsWith("|")) break;
      const cells = cellsOf(lines[row]);
      if (cells.length !== 5) continue;
      const [name, type, required, fallback, description] = cells;
      const optional = required === "no" ? "?" : "";
      const withDefault =
        fallback === "" || fallback === "–" || fallback === "-"
          ? description
          : `${description.replace(/\s+$/, "")}${/[.!?]$/.test(description) ? "" : "."} Default: ${fallback}.`;
      lines[row] = `| ${name}${optional} | ${type} | ${withDefault} |`;
    }
  }

  return lines.join("\n");
};

/**
 * Where every published page is written, keyed by source, plus the reverse
 * lookups the link rewriter needs.
 */
export const layout = (categories, storyId) => {
  const bySource = new Map();
  const byStoryId = new Map();

  const visit = (category) => {
    const index = `${category.slug}/index.md`;
    if (category.readme) bySource.set(category.readme.source, index);
    for (const page of category.pages) {
      const out = `${category.slug}/${page.slug}.md`;
      bySource.set(page.source, out);
      if (page.title) byStoryId.set(storyId(page.title), out);
    }
    byStoryId.set(storyId(category.key), index);
    category.children.forEach(visit);
  };
  categories.forEach(visit);

  return { bySource, byStoryId };
};

/** The overview rows of a category's children, for its page and the root's. */
const childRows = (categories, prefix = "./") =>
  categories.map((category) => {
    const section = SECTIONS[category.key];
    return {
      label: section?.title ?? category.label,
      link: `${prefix}${category.slug.split("/").at(-1)}/index.md`,
      summary: section
        ? firstSentence(section.description)
        : (category.readme?.meta?.summary ?? ""),
    };
  });

const relativeLink = (from, to) => {
  const link = path.posix.relative(path.posix.dirname(from), to);
  return link.startsWith(".") ? link : `./${link}`;
};

/**
 * The link rewriter for one page. Returns the `resolve` callback of
 * `rewriteLinks`.
 */
export const linkResolver = ({ root, source, out, pages, revision, warn }) => {
  const blob = (kind, file, hash) =>
    `${REPO_URL}/${kind}/${revision}/${file}${hash}`;

  return (target, label, isImage) => {
    if (/^[a-z][a-z0-9+.-]*:/i.test(target) || target.startsWith("//")) {
      return undefined;
    }
    if (target.startsWith("#")) return undefined;

    const storybook = /^\?path=\/(?:docs|story)\/([^&#]+)/.exec(target);
    if (storybook) {
      const id = storybook[1].replace(/--[^-].*$/, "");
      const page = pages.byStoryId.get(id);
      if (page) return relativeLink(out, page);
      const base = storybookUrl();
      if (base) return `${base}/${target}`;
      warn(
        `${source}: Storybook link "${target}" has no page here; link removed`,
      );
      return null;
    }

    const hashAt = target.indexOf("#");
    const file = hashAt === -1 ? target : target.slice(0, hashAt);
    const hash = hashAt === -1 ? "" : target.slice(hashAt);
    const resolved = path.posix.normalize(
      path.posix.join(path.posix.dirname(source), decodeURI(file)),
    );

    const direct =
      pages.bySource.get(resolved) ??
      pages.bySource.get(path.posix.join(resolved, "README.md"));
    if (direct && !isImage) return relativeLink(out, direct) + hash;

    const full = path.join(root, resolved);
    if (resolved.startsWith("..") || !fs.existsSync(full)) {
      warn(
        `${source}: link "${label}" points at "${target}", which does not exist`,
      );
      return undefined;
    }
    if (isImage) {
      return `${REPO_URL}/raw/${revision}/${resolved}`;
    }
    return blob(
      fs.statSync(full).isDirectory() ? "tree" : "blob",
      resolved,
      hash,
    );
  };
};

/**
 * Wraps every table of a page in the site's <APITable>, as docspace-sdk-js
 * does: rows become addressable by the text of their first cell. A table
 * with an empty first cell somewhere is left alone -- the component throws
 * on a row it cannot name. Tables are named when their row ids collide.
 */
export const wrapApiTables = (text) => {
  const lines = splitLines(text);
  const tables = [];
  let heading = "";

  for (let index = 0; index < lines.length; index += 1) {
    const { text: line, code } = lines[index];
    if (code) continue;
    const match = /^#{2,6}\s+(.*)$/.exec(line);
    if (match) heading = match[1].trim();
    if (!/^\|/.test(line)) continue;
    if (!/^\|[\s:|-]+\|$/.test(lines[index + 1]?.text ?? "")) continue;

    let end = index + 2;
    while (end < lines.length && /^\|/.test(lines[end].text)) end += 1;
    // The row id the component derives: the first cell's first child's
    // text -- a code span's content, a link's text, or the plain text. A
    // cell that opens with an image or an HTML element has no text there,
    // and the component throws at site build, so the table stays plain.
    const ids = lines.slice(index + 2, end).map(({ text: row }) => {
      const cell = /^\|\s*((?:\\\||[^|])*?)\s*\|/.exec(row)?.[1] ?? "";
      if (/^(!\[|<)/.test(cell)) return "";
      const code = /^`([^`]+)`/.exec(cell)?.[1];
      const link = /^\[`?([^`\]]+)`?\]/.exec(cell)?.[1];
      return code ?? link ?? cell.replace(/[`*_]/g, "").trim();
    });
    const start = index;
    index = end - 1;
    if (ids.some((id) => id === "")) continue;
    tables.push({ start, end, heading, ids });
  }

  if (tables.length === 0) return { text, wrapped: false };

  const all = tables.flatMap((table) => table.ids);
  const collide = new Set(all).size !== all.length;
  const out = lines.map(({ text: line }) => line);

  for (const table of [...tables].reverse()) {
    const name = collide
      ? ` name="${table.heading.replace(/[^\w-]+/g, "-").replace(/^-|-$/g, "")}"`
      : "";
    out.splice(table.end, 0, "", "</APITable>");
    out.splice(table.start, 0, `<APITable${name}>`, "");
  }

  return { text: out.join("\n"), wrapped: true };
};

const addImport = (text, line) => `${line}\n\n${text}`;

const storybookLine = (title) => {
  const base = storybookUrl();
  return base && title
    ? `[Open in Storybook](${base}/?path=/docs/${title})`
    : null;
};

/**
 * Storybook's args table as the three-column Props table the README pages
 * carry: the optional marker outside the code span, the default closing the
 * description.
 */
const controlsTable = (rows) =>
  rows.length === 0
    ? ""
    : [
        "| Property | Type | Description |",
        "| --- | --- | --- |",
        ...rows.map((row) => {
          // Scraped from the page, so prose: escaped like any other.
          const text = escapeForMdx(row.description ?? "");
          const sentence = text && !/[.!?]$/.test(text) ? `${text}.` : text;
          const description = [
            sentence,
            row.default ? `Default: \`${row.default}\`.` : "",
          ]
            .filter(Boolean)
            .join(" ");
          const type = row.type ? `\`${cell(row.type)}\`` : "";
          const name = `\`${row.name}\`${row.required ? "" : "?"}`;
          return `| ${name} | ${type} | ${cell(description)} |`;
        }),
      ].join("\n");

/** The picture of a page's `name` shot, or nothing when it was not taken. */
const pictureOf = (pictures, name, alt) =>
  pictures?.has(name) ? themedImage(alt, pictures.get(name)) : null;

/**
 * Storybook's Stories block: every story of the page's CSF file, with its
 * name, its `docs.description.story` and its picture.
 */
const storiesSection = (page, pictures) => {
  const stories = page.stories ?? [];
  if (stories.length === 0) return "";
  const parts = ["## Stories", ""];
  for (const story of stories) {
    const name = storyNameFromExport(story.exportName);
    parts.push(`### ${name}`, "");
    if (story.description) parts.push(escapeForMdx(story.description), "");
    const picture = pictureOf(pictures, storyKey(story.exportName), name);
    if (picture) parts.push(picture, "");
  }
  return parts.join("\n").trimEnd();
};

/** The README's reference half starts here; Storybook puts the stories before it. */
const REFERENCE_FROM = "\n## Minimal example";

/** The warning a portal-only page opens with, linking to the Public API page. */
const portalNote = ({ page, out, pages, revision }) => {
  if (!page.portalOnly) return null;
  const target = pages?.bySource.get(PUBLIC_API_FILE);
  const link = target
    ? relativeLink(out, target)
    : `${REPO_URL}/blob/${revision}/${PUBLIC_API_FILE}`;
  return [
    ":::warning[Portal only]",
    "",
    "Works only inside an ONLYOFFICE Apps portal: it needs the portal's API " +
      "client, stores and translations, and is not part of the " +
      `[public API](${link}).`,
    "",
    ":::",
  ].join("\n");
};

/** Inserts `block` right after the H1. */
const afterH1 = (text, block) => {
  if (!block) return text;
  const lines = text.split("\n");
  const h1 = lines.findIndex((l) => /^# /.test(l));
  lines.splice(h1 + 1, 0, "", block);
  return lines.join("\n");
};

/** Inserts `line` after the first paragraph that follows the H1. */
const afterIntro = (text, line) => {
  if (!line) return text;
  const lines = text.split("\n");
  const h1 = lines.findIndex((l) => /^# /.test(l));
  let index = h1 + 1;
  while (index < lines.length && lines[index].trim() === "") index += 1;
  while (index < lines.length && lines[index].trim() !== "") index += 1;
  lines.splice(index, 0, "", line);
  return lines.join("\n");
};

/** A README, rewritten. */
export const renderReadme = (raw, context) => {
  const { page, pictures, revision, storyId } = context;
  let text = stripHtmlComments(raw).replace(GENERATED_NOTE, "").trim();
  text = rewriteLinks(text, linkResolver(context));
  text = escapeForMdx(text);
  text = reshapePropsTables(text);
  text = afterH1(text, portalNote(context));
  text = afterIntro(
    text,
    storybookLine(page.title ? `${storyId(page.title)}--docs` : null),
  );
  // Inserted after the link, so it lands first: right under the intro.
  text = afterIntro(text, pictureOf(pictures, "primary", page.label));
  const stories = storiesSection(page, pictures);
  if (stories) {
    const at = text.indexOf(REFERENCE_FROM);
    text =
      at === -1
        ? `${text}\n\n${stories}`
        : `${text.slice(0, at).trimEnd()}\n\n${stories}\n${text.slice(at)}`;
  }
  const tables = wrapApiTables(text);
  text = tables.wrapped
    ? addImport(tables.text, API_TABLE_IMPORT)
    : tables.text;
  if (text.includes("<ThemedImage"))
    text = addImport(text, THEMED_IMAGE_IMPORT);

  return (
    frontMatter({
      description: page.meta?.summary,
      custom_edit_url: `${REPO_URL}/blob/${revision}/${page.source}`,
    }) +
    text +
    "\n"
  );
};

/**
 * The generated page of a CSF file with neither a README nor an MDX docs
 * page: what Storybook's autodocs shows -- title, description, the primary
 * story, the args table, the stories.
 */
export const renderAutodocs = (raw, context) => {
  const { page, pictures, revision } = context;
  const parts = [`# ${page.label}`, ""];
  const note = portalNote(context);
  if (note) parts.push(note, "");
  if (page.description) parts.push(escapeForMdx(page.description), "");
  const primary = pictureOf(pictures, "primary", page.label);
  if (primary) parts.push(primary, "");
  const controls = pictures?.get("args-table")?.rows;
  if (controls?.length) parts.push("## Props", "", controlsTable(controls), "");
  const stories = storiesSection(page, pictures);
  if (stories) parts.push(stories, "");
  let text = parts.join("\n").trimEnd();
  const tables = wrapApiTables(text);
  text = tables.wrapped
    ? addImport(tables.text, API_TABLE_IMPORT)
    : tables.text;
  if (text.includes("<ThemedImage"))
    text = addImport(text, THEMED_IMAGE_IMPORT);
  return (
    frontMatter({
      description: summaryOf(page, raw),
      custom_edit_url: `${REPO_URL}/blob/${revision}/${page.source}`,
    }) +
    text +
    "\n"
  );
};

/**
 * A Storybook MDX page -- a docs page of a CSF file or a page of its own --
 * with every React element replaced by its picture: a story by the story's,
 * anything else by the element's as the Docs page renders it.
 */
export const renderMdx = (raw, context) => {
  const { page, pictures, revision, assets, warn } = context;
  const { blocks, lines, imports } = parseMdx(raw);
  const kept = [];
  let blockIndex = 0;
  let cursor = 0;

  for (const block of blocks) {
    for (; cursor < block.start; cursor += 1) kept.push(lines[cursor].text);
    cursor = block.end + 1;
    if (block.tag === "import" || block.tag === "Meta") continue;
    if (/^[a-z]/.test(block.tag)) {
      // An HTML element: its string attributes stay; `src={walkthrough}`
      // becomes the imported file, copied beside the page; anything else
      // computed is dropped.
      const attrs = Object.entries(block.attrs).map(([k, v]) => `${k}="${v}"`);
      const source =
        block.expressions?.src && imports.get(block.expressions.src);
      if (source) {
        const from = path.posix.join(path.posix.dirname(page.source), source);
        const name = path.posix.basename(from);
        if (fs.existsSync(path.join(context.root, from))) {
          assets?.set(name, from);
          attrs.push(`src={require('./${name}').default}`);
        } else {
          warn?.(
            `${page.source}: <${block.tag} src={${block.expressions.src}}> points at ${from}, which does not exist`,
          );
        }
      }
      const open = `<${block.tag}${attrs.length ? ` ${attrs.join(" ")}` : ""}`;
      kept.push(
        block.children
          ? `${open}>${block.children}</${block.tag}>`
          : `${open} />`,
      );
      continue;
    }
    if (block.tag in BLOCK_RENDERERS) {
      kept.push(BLOCK_RENDERERS[block.tag](context.root, block));
      continue;
    }
    let picture;
    if (block.tag === "Story" && block.of) {
      const exportName = block.of.split(".").at(-1);
      picture = pictureOf(
        pictures,
        storyKey(exportName),
        storyNameFromExport(exportName),
      );
    } else if (block.tag === "Controls") {
      const rows = pictures?.get("args-table")?.rows;
      if (rows?.length) kept.push(controlsTable(rows));
      continue;
    } else {
      picture = pictureOf(pictures, `block${blockIndex}`, block.tag);
      blockIndex += 1;
    }
    if (picture) kept.push(picture);
  }
  for (; cursor < lines.length; cursor += 1) kept.push(lines[cursor].text);

  let text = kept
    .join("\n")
    .replace(/\n{3,}/g, "\n\n")
    .trim();
  // A trailing rule and the paragraph after it is the page's Storybook
  // footer -- the package version and licence under Welcome. The site has a
  // footer of its own.
  text = text.replace(/\n---\n+(?:[^\n]+\n?)+$/, "").trimEnd();
  // The other rules go too: Docusaurus draws them as a line across the
  // page, between sections that have headings already.
  text = splitLines(text)
    .filter(
      ({ text: line, code }) =>
        code || !/^\s*(-{3,}|\*{3,}|_{3,})\s*$/.test(line),
    )
    .map(({ text: line }) => line)
    .join("\n")
    .replace(/\n{3,}/g, "\n\n");
  text = rewriteLinks(text, linkResolver(context));
  // A page whose heading was part of the dropped component still needs one:
  // Docusaurus titles the page from its H1.
  if (!headings(text).some(({ depth }) => depth === 1)) {
    text = `# ${page.label}\n\n${text}`;
  }
  text = afterH1(text, portalNote(context));
  const tables = wrapApiTables(text);
  text = tables.wrapped
    ? addImport(tables.text, API_TABLE_IMPORT)
    : tables.text;
  if (text.includes("<ThemedImage"))
    text = addImport(text, THEMED_IMAGE_IMPORT);

  return (
    frontMatter({
      description: summaryOf(page, raw),
      custom_edit_url: `${REPO_URL}/blob/${revision}/${page.source}`,
    }) +
    text +
    "\n"
  );
};

/** A plain Markdown file from `docs/`. */
export const renderMarkdown = (raw, context) => {
  const { page, revision } = context;
  let text = stripHtmlComments(raw).trim();
  text = rewriteLinks(text, linkResolver(context));
  text = escapeForMdx(text);
  return (
    frontMatter({
      description: summaryOf(page, raw),
      custom_edit_url: `${REPO_URL}/blob/${revision}/${page.source}`,
    }) +
    text +
    "\n"
  );
};

/** What the overview table says about a page. */
export const summaryOf = (page, raw) =>
  page.meta?.summary ??
  page.options?.summary ??
  (page.description
    ? firstSentence(firstParagraph(page.description))
    : undefined) ??
  (page.kind === "autodocs"
    ? ""
    : firstSentence(
        firstParagraph(
          stripHtmlComments(raw)
            .replace(/\{\/\*[\s\S]*?\*\/\}/g, "")
            .replace(/^import .*$/gm, ""),
        ),
      ));

const overviewTable = (caption, header, rows, { code = true } = {}) =>
  [
    caption,
    "",
    `| ${header} | Description |`,
    "| --- | --- |",
    ...rows.map(
      ({ label, link, summary }) =>
        `| [${code ? `\`${cell(label)}\`` : cell(label)}](${link}) | ${cell(summary)} |`,
    ),
  ].join("\n");

/** The page of a category: its README when it has one, sections.mjs otherwise. */
export const renderCategory = (category, context) => {
  const { revision, summaries, warn } = context;
  const section = SECTIONS[category.key];
  const rows = (category.sequence ?? []).map(({ type, item }) =>
    type === "category"
      ? childRows([item])[0]
      : {
          label: item.label,
          link: `./${item.slug}.md`,
          summary: summaries.get(item.source) ?? "",
        },
  );
  const table = overviewTable(
    section?.tableCaption ?? DEFAULT_TABLE_CAPTION,
    section?.tableHeader ?? DEFAULT_TABLE_HEADER,
    rows,
    // Component names are code; group and page titles are not.
    {
      code:
        category.children.length === 0 &&
        category.pages.every((page) => page.kind === "readme"),
    },
  );

  if (category.readme) {
    const body = renderReadme(context.readmeText, {
      ...context,
      page: category.readme,
    });
    return rows.length > 0
      ? `${body.trimEnd()}\n\n## In this section\n\n${escapeForMdx(table)}\n`
      : body;
  }

  if (!section) {
    warn(`category "${category.key}" has no entry in ${SECTIONS_FILE}`);
  }

  return (
    frontMatter({
      custom_edit_url: `${REPO_URL}/blob/${revision}/${SECTIONS_FILE}`,
    }) +
    `# ${section?.title ?? category.label}\n\n` +
    (section ? `${section.description}\n\n` : "") +
    "## Overview\n\n" +
    escapeForMdx(table) +
    "\n"
  );
};

/** The landing page of the section. */
export const renderRoot = (categories, { revision }) => {
  const rows = childRows(categories);

  return (
    frontMatter({
      custom_edit_url: `${REPO_URL}/blob/${revision}/${SECTIONS_FILE}`,
    }) +
    `# ${ROOT_SECTION.title}\n\n${ROOT_SECTION.description}\n\n` +
    escapeForMdx(
      overviewTable(ROOT_SECTION.tableCaption, ROOT_SECTION.tableHeader, rows, {
        code: false,
      }),
    ) +
    "\n"
  );
};
