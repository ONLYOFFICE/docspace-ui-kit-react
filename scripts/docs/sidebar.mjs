// The Docusaurus sidebar for the section, in the shape docspace-sdk-js emits:
// a CommonJS module exporting an items array that the site's `sidebars.ts`
// spreads into its own category.

import { PATH_PREFIX } from "./config.mjs";
import { SECTIONS } from "./sections.mjs";

const docId = (file) => `${PATH_PREFIX}/${file.replace(/\.md$/, "")}`;

export const sidebarItems = (categories) =>
  categories.map((category) => ({
    type: "category",
    label: SECTIONS[category.key]?.title ?? category.label,
    link: { type: "doc", id: docId(`${category.slug}/index.md`) },
    items: category.pages.map((page) => ({
      type: "doc",
      id: docId(`${category.slug}/${page.slug}.md`),
      label: page.label,
    })),
  }));

export const renderSidebar = (categories) =>
  [
    "// @ts-check",
    "// Generated by `pnpm docs` in @onlyoffice/apps-ui-kit. Do not edit.",
    '/** @type {import("@docusaurus/plugin-content-docs").SidebarsConfig} */',
    `const uiKitSidebar = { items: ${JSON.stringify(sidebarItems(categories), null, 2)} };`,
    "module.exports = uiKitSidebar.items;",
    "",
  ].join("\n");
